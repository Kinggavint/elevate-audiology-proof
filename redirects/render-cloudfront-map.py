#!/usr/bin/env python3
"""Turn redirects/store-map.csv into the repo's redirect mechanism WITHOUT wiring it in.

The live mechanism is the CloudFront Function `elevate-audiology-redirects`
(infra/cloudfront-redirects.js, viewer-request, 10,240-byte cap; the deployed min.js is
already ~10 KB, so a literal 153-entry map does NOT fit). Two outputs:

  redirects/store-map.generated.js   snippet for the function: keyword rules + 410 fallback
                                     (fits the cap); --mode map|accessories|gone
  redirects/store-map.kvs.json       exact per-URL map in CloudFront KeyValueStore import
                                     format, if the function is moved to KVS lookups

Nothing is written to infra/ or AWS. Usage:
    python3 redirects/render-cloudfront-map.py --mode map          # option A/B hybrid: 301 by rule, 410 the rest
    python3 redirects/render-cloudfront-map.py --mode accessories --to /accessories/   # option B
    python3 redirects/render-cloudfront-map.py --mode gone         # option C: everything 410
"""
import csv, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "store-map.csv")
mode = sys.argv[sys.argv.index("--mode") + 1] if "--mode" in sys.argv else "map"
to = sys.argv[sys.argv.index("--to") + 1] if "--to" in sys.argv else "/batteries/"

rows = list(csv.DictReader(open(SRC)))
kvs = {"data": [{"key": r["old_path"], "value": (to if mode == "accessories" else "410" if mode == "gone" else r["destination"])} for r in rows]}
json.dump(kvs, open(os.path.join(HERE, "store-map.kvs.json"), "w"), indent=1)

GONE = "return { statusCode: 410, statusDescription: 'Gone' };"
def r301(dest):
    return "return { statusCode: 301, statusDescription: 'Moved Permanently', headers: { location: { value: '%s' } } };" % dest

lines = ["  // Retired WooCommerce store (generated by redirects/render-cloudfront-map.py --mode %s; do not hand-edit)" % mode,
         "  if (uri.indexOf('/product/') === 0 || uri.indexOf('/product-category/') === 0) {"]
if mode == "gone":
    lines.append("    " + GONE)
elif mode == "accessories":
    lines.append("    " + r301(to))
else:
    # keyword rules mirror build-store-map.py; only high/medium rows get a 301, low rows go 410
    import re
    from collections import OrderedDict
    groups = OrderedDict()
    for r in rows:
        if r["confidence"] == "low":
            continue
        groups.setdefault(r["destination"], []).append(r["old_path"].strip("/").split("/", 1)[1])
    lines.append("    var s = uri;")
    for dest, slugs in groups.items():
        # shortest distinguishing keywords per destination, taken from the rule names
        kws = sorted({k for s in slugs for k in re.findall(r"[a-z]+", s) if k in (
            "battery", "batteries", "tinnitus", "lenire", "dome", "domes", "tip", "tips", "sleeve", "wax", "cerustop",
            "cerushield", "hf4", "prowax", "nanocare", "guard", "guards", "filter", "filters", "cleaning", "brush",
            "dryer", "dehumidifier", "dry", "dessicants", "audiowipes", "eardrops", "audgel", "gear", "planes", "tube", "tubing", "earmold", "retention", "clip", "cover", "covers", "charger",
            "charging", "case", "receiver", "receivers", "wire", "oticon", "phonak", "resound", "signia", "starkey",
            "unitron", "widex", "sonic", "rexton", "bernafon", "philips")})
        if not kws:
            continue
        cond = " || ".join("s.indexOf('%s') !== -1" % k for k in kws)
        lines.append("    if (%s) { %s }" % (cond, r301(dest)))
    lines.append("    " + GONE + "  // unmapped: nothing on the live site covers it")
lines.append("  }")
out = os.path.join(HERE, "store-map.generated.js")
open(out, "w").write("\n".join(lines) + "\n")
print(f"wrote {out} ({os.path.getsize(out)} bytes) and store-map.kvs.json ({len(rows)} keys), mode={mode}")
